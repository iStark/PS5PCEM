fn populatePointers(registers: anytype, offsets: anytype, pointers: anytype) void {
    for (offsets, 0..) |offset, index| pointers[index] = registers[@as(usize, offset)..].ptr;
}

fn initialize() void {
    while (!defaults_mutex.tryLock()) std.atomic.spinLoopHint();
    defer defaults_mutex.unlock();
    if (defaults_initialized) return;

    populatePointers(&primary_table0_registers, &primary_table0_offsets, &primary_table0_pointers);
    populatePointers(&primary_table1_registers, &primary_table1_offsets, &primary_table1_pointers);
    populatePointers(&primary_table2_registers, &primary_table2_offsets, &primary_table2_pointers);
    populatePointers(&internal_table0_registers, &internal_table0_offsets, &internal_table0_pointers);
    populatePointers(&internal_table1_registers, &internal_table1_offsets, &internal_table1_pointers);
    populatePointers(&internal_table2_registers, &internal_table2_offsets, &internal_table2_pointers);
    populatePointers(&internal_table3_registers, &internal_table3_offsets, &internal_table3_pointers);

    primary_defaults = .{
        .tables = .{ primary_table0_pointers[0..].ptr, primary_table1_pointers[0..].ptr, primary_table2_pointers[0..].ptr, null },
        .register_counts = .{ primary_table0_registers.len, primary_table1_registers.len, primary_table2_registers.len, 0 },
        .types = primary_types[0..].ptr,
        .type_count = primary_types.len / 3,
    };
    internal_defaults = .{
        .tables = .{ internal_table0_pointers[0..].ptr, internal_table1_pointers[0..].ptr, internal_table2_pointers[0..].ptr, internal_table3_pointers[0..].ptr },
        .register_counts = .{ internal_table0_registers.len, internal_table1_registers.len, internal_table2_registers.len, internal_table3_registers.len },
        .types = internal_types[0..].ptr,
        .type_count = internal_types.len / 3,
    };
    defaults_initialized = true;
}

pub fn get(version: u32, internal: bool) *anyopaque {
    // Version 10 is the native table used by current titles. Until the
    // adjacent revisions are embedded, prefer this complete state over an
    // empty table; the ABI and all tracked Gen5 offsets are compatible.
    _ = version;
    initialize();
    return if (internal) @ptrCast(&internal_defaults) else @ptrCast(&primary_defaults);
}

test "version 10 defaults expose complete pointer tables" {
    const primary: *const RegisterDefaults = @ptrCast(@alignCast(get(10, false)));
    const internal: *const RegisterDefaults = @ptrCast(@alignCast(get(10, true)));
    try std.testing.expectEqual(@as(u32, 482), primary.register_counts[0]);
    try std.testing.expectEqual(@as(u32, 128), primary.type_count);
    try std.testing.expectEqual(@as(u32, 9), internal.register_counts[0]);
    try std.testing.expectEqual(@as(u32, 28), internal.type_count);
    try std.testing.expectEqual(@as(u32, 0x318), primary.tables[0].?[73][0].offset);
    try std.testing.expectEqual(@as(u32, 0x10f), primary.tables[0].?[77][0].offset);
}
