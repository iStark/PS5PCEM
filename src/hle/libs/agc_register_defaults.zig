    offset: u32,
    value: u32,
};

const RegisterPointer = [*]const ShaderRegister;

const RegisterDefaults = extern struct {
    tables: [4]?[*]const RegisterPointer,
    register_counts: [4]u32,
    types: [*]const u32,
    type_count: u32,
    padding: u32 = 0,
};

comptime {
    if (@sizeOf(RegisterDefaults) != 0x40 or @offsetOf(RegisterDefaults, "type_count") != 0x38)
        @compileError("unexpected AGC register-default ABI layout");
}

