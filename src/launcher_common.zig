/// Major, minor and patch of a tag such as "v0.3.4" or "0.3.1-beta.1". Missing
/// components read as zero, and a pre-release suffix is ignored.
pub fn parseReleaseVersion(tag: []const u8) ?[3]u32 {
    const digits = versionDigits(tag);
    var parts: [3]u32 = .{ 0, 0, 0 };
    var cursor: usize = 0;
    for (&parts, 0..) |*part, index| {
        const start = cursor;
        while (cursor < digits.len and std.ascii.isDigit(digits[cursor])) : (cursor += 1) {}
        if (cursor == start) return if (index == 0) null else parts;
        part.* = std.fmt.parseInt(u32, digits[start..cursor], 10) catch return null;
        if (cursor >= digits.len or digits[cursor] != '.') break;
        cursor += 1;
    }
    return parts;
}

pub fn versionDigits(tag: []const u8) []const u8 {
    return if (tag.len != 0 and (tag[0] == 'v' or tag[0] == 'V')) tag[1..] else tag;
}

pub fn isNewerRelease(remote: [3]u32, local: [3]u32) bool {
    return std.mem.order(u32, &remote, &local) == .gt;
}

/// Finds a quoted string value following a quoted key.
pub fn jsonStringValue(document: []const u8, quoted_key: []const u8) ?[]const u8 {
    const key_at = std.mem.indexOf(u8, document, quoted_key) orelse return null;
    var cursor = key_at + quoted_key.len;
    while (cursor < document.len and (document[cursor] == ' ' or document[cursor] == '\t')) cursor += 1;
    if (cursor >= document.len or document[cursor] != ':') return null;
    cursor += 1;
    while (cursor < document.len and
        (document[cursor] == ' ' or document[cursor] == '\t' or
            document[cursor] == '\r' or document[cursor] == '\n')) cursor += 1;
    if (cursor >= document.len or document[cursor] != '"') return null;
    const start = cursor + 1;
    const end = std.mem.indexOfScalarPos(u8, document, start, '"') orelse return null;
    return document[start..end];
}

/// What the host can actually do, rather than what the launcher hopes.
///
/// The status line asserted "Vulkan VideoOut" unconditionally. A machine with
/// no loader, no device, or a driver below the 1.2 the renderer requires read
/// exactly the same, and the person only found out when the emulator exited
/// without a window. Ask the loader instead, once, at startup.
pub const VulkanReport = struct {
    pub const State = enum { unchecked, no_loader, no_device, too_old, ready };

    state: State = .unchecked,
    device: [256]u8 = @splat(0),
    device_length: usize = 0,
    major: u32 = 0,
    minor: u32 = 0,

    pub fn deviceName(self: *const VulkanReport) []const u8 {
        return self.device[0..self.device_length];
    }
};

pub const GetInstanceProcAddr = *const fn (usize, [*:0]const u8) callconv(.c) ?*anyopaque;

const VulkanApplicationInfo = extern struct {
    s_type: u32 = 0,
    p_next: ?*const anyopaque = null,
    application_name: ?[*:0]const u8 = null,
    application_version: u32 = 0,
    engine_name: ?[*:0]const u8 = null,
    engine_version: u32 = 0,
    api_version: u32,
};

const VulkanInstanceCreateInfo = extern struct {
    s_type: u32 = 1,
    p_next: ?*const anyopaque = null,
    flags: u32 = 0,
    application_info: ?*const VulkanApplicationInfo,
    enabled_layer_count: u32 = 0,
    enabled_layer_names: ?[*]const [*:0]const u8 = null,
    enabled_extension_count: u32 = 0,
    enabled_extension_names: ?[*]const [*:0]const u8 = null,
};

/// The fields read here, followed by room for the rest of the structure. The
/// driver writes all of VkPhysicalDeviceProperties, about 824 bytes with every
/// device limit, so a declaration of the prefix alone would let it write past
/// the end of the stack slot. The limits are not transcribed: nothing else here
/// reads them.
const VulkanProperties = extern struct {
    api_version: u32,
    driver_version: u32,
    vendor_id: u32,
    device_id: u32,
    device_type: u32,
    device_name: [256]u8,
    remainder: [1024]u8,
};

/// Asks the loader behind `get_instance_proc` for an instance and a device.
/// Loading the library is the caller's: each host finds it differently.
pub fn probeVulkan(get_instance_proc_address: ?GetInstanceProcAddr) VulkanReport {
    var report: VulkanReport = .{};
    const get_instance_proc = get_instance_proc_address orelse {
        report.state = .no_loader;
        return report;
    };
    const create_instance = @as(
        ?*const fn (*const VulkanInstanceCreateInfo, ?*anyopaque, *usize) callconv(.c) i32,
        @ptrCast(get_instance_proc(0, "vkCreateInstance")),
    ) orelse {
        report.state = .no_loader;
        return report;
    };

    // 1.2 is what the renderer itself requires, so asking for less here would
    // report a machine as ready that the emulator then refuses.
    const application = VulkanApplicationInfo{ .api_version = (1 << 22) | (2 << 12) };
    const create_info = VulkanInstanceCreateInfo{ .application_info = &application };
    var instance: usize = 0;
    if (create_instance(&create_info, null, &instance) != 0 or instance == 0) {
        report.state = .too_old;
        return report;
    }
    defer {
        if (@as(
            ?*const fn (usize, ?*anyopaque) callconv(.c) void,
            @ptrCast(get_instance_proc(instance, "vkDestroyInstance")),
        )) |destroy| destroy(instance, null);
    }

    const enumerate = @as(
        ?*const fn (usize, *u32, ?[*]usize) callconv(.c) i32,
        @ptrCast(get_instance_proc(instance, "vkEnumeratePhysicalDevices")),
    ) orelse {
        report.state = .no_device;
        return report;
    };
    var count: u32 = 0;
    if (enumerate(instance, &count, null) != 0 or count == 0) {
        report.state = .no_device;
        return report;
    }
    var devices: [8]usize = @splat(0);
    count = @min(count, devices.len);
    // VK_INCOMPLETE (5) only says the array was shorter than the device list.
    const listed = enumerate(instance, &count, &devices);
    if ((listed != 0 and listed != 5) or count == 0) {
        report.state = .no_device;
        return report;
    }

    report.state = .ready;
    const properties_of = @as(
        ?*const fn (usize, *VulkanProperties) callconv(.c) void,
        @ptrCast(get_instance_proc(instance, "vkGetPhysicalDeviceProperties")),
    ) orelse return report;
    var properties: VulkanProperties = undefined;
    properties_of(devices[0], &properties);
    report.major = (properties.api_version >> 22) & 0x7f;
    report.minor = (properties.api_version >> 12) & 0x3ff;
    for (properties.device_name, 0..) |byte, index| {
        if (byte == 0) {
            report.device_length = index;
            break;
        }
        report.device[index] = byte;
        report.device_length = index + 1;
    }
    return report;
}

test "release tags compare by major, minor and patch" {
    try std.testing.expectEqual([3]u32{ 0, 3, 4 }, parseReleaseVersion("v0.3.4").?);
    try std.testing.expectEqual([3]u32{ 0, 3, 1 }, parseReleaseVersion("0.3.1-beta.1").?);
    try std.testing.expectEqual([3]u32{ 1, 0, 0 }, parseReleaseVersion("v1").?);
    try std.testing.expectEqual([3]u32{ 0, 10, 0 }, parseReleaseVersion("0.10").?);
    try std.testing.expectEqual(@as(?[3]u32, null), parseReleaseVersion("latest"));
    try std.testing.expectEqual(@as(?[3]u32, null), parseReleaseVersion(""));
    try std.testing.expect(isNewerRelease(.{ 0, 3, 5 }, .{ 0, 3, 4 }));
    try std.testing.expect(isNewerRelease(.{ 0, 10, 0 }, .{ 0, 9, 9 }));
    try std.testing.expect(!isNewerRelease(.{ 0, 3, 4 }, .{ 0, 3, 4 }));
    try std.testing.expect(!isNewerRelease(.{ 0, 3, 3 }, .{ 0, 3, 4 }));
}
